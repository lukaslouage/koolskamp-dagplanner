"""Builds data/route-data.js from the GPX files in data/gpx.

Run from the project folder:  python3 tools/build_route_data.py

A course is a start place with an optional loop (ridden 0 or more times, it starts and ends at the start) and an
approach from the start to the finish line in Koolskamp. Every race ends with laps of the local circuit.
The point where an approach joins the local circuit is found automatically; for the original Ardooie course the
official distances are used, for the others the GPX length (rounded to 0,1 km).
"""
import json
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GPX = os.path.join(ROOT, 'data', 'gpx')

LOCAL_LAP = 'local-lap.gpx'
COURSES = [
    {'id': 'ardooie', 'name': 'Ardooie', 'start': 'Ardooie',
     'loop': {'file': 'ardooie-loop.gpx', 'km': 16},
     'approach': {'file': 'approach-to-finish.gpx', 'km': 12.5, 'joinKm': 10.7, 'joinName': 'Kruiskalsijde'}},
    {'id': 'ardooie-groot', 'name': 'Ardooie, grote lus', 'start': 'Ardooie',
     'loop': {'file': 'ardooie-big-loop.gpx'},
     'approach': {'file': 'approach-to-finish.gpx', 'km': 12.5, 'joinKm': 10.7, 'joinName': 'Kruiskalsijde'}},
    {'id': 'ieper', 'name': 'Ieper', 'start': 'Ieper',
     'loop': None,
     'approach': {'file': 'ieper-approach.gpx', 'joinName': 'Aansluiting circuit'}},
]
JOIN_METRES = 25  # an approach counts as being on the circuit within this distance of it


def read(name):
    text = open(os.path.join(GPX, name), encoding='utf-8').read()
    points = []
    for lat, lon, body in re.findall(r'<trkpt lat="([-\d.]+)" lon="([-\d.]+)">(.*?)</trkpt>', text, re.S):
        ele = re.search(r'<ele>([-\d.]+)</ele>', body)
        points.append([round(float(lat), 5), round(float(lon), 5), round(float(ele.group(1)), 1) if ele else 0])
    return points


def haversine(a, b):
    t = math.pi / 180
    x = math.sin((b[0] - a[0]) * t / 2) ** 2 + math.cos(a[0] * t) * math.cos(b[0] * t) * math.sin((b[1] - a[1]) * t / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(x))


def length(points):
    return sum(haversine(points[i - 1], points[i]) for i in range(1, len(points)))


def distance_to_line(p, line):
    """Metres from p to the nearest stretch of a polyline (flat approximation, fine at this scale)."""
    def xy(q):
        return ((q[1] - p[1]) * 111320 * math.cos(math.radians(p[0])), (q[0] - p[0]) * 110540)
    best = float('inf')
    for i in range(1, len(line)):
        (ax, ay), (bx, by) = xy(line[i - 1]), xy(line[i])
        dx, dy = bx - ax, by - ay
        span = dx * dx + dy * dy
        t = 0 if span == 0 else max(0, min(1, -(ax * dx + ay * dy) / span))
        best = min(best, math.hypot(ax + t * dx, ay + t * dy))
    return best


def find_join(approach, lap):
    """Index of the first point of the last stretch of the approach that stays on the local circuit."""
    k = len(approach) - 1
    while k > 0 and distance_to_line(approach[k - 1], lap) < JOIN_METRES:
        k -= 1
    return k


def main():
    lap = read(LOCAL_LAP)
    routes = {'local-lap': lap}
    courses = {}
    for c in COURSES:
        course = {'name': c['name'], 'start': c['start'], 'loop': None}
        if c['loop']:
            route_id = c['loop']['file'][:-4]
            routes[route_id] = routes.get(route_id) or read(c['loop']['file'])
            course['loop'] = {'route': route_id, 'km': c['loop'].get('km') or round(length(routes[route_id]), 1)}
        a = c['approach']
        route_id = a['file'][:-4]
        points = routes.get(route_id) or read(a['file'])
        routes[route_id] = points
        gpx_km = length(points)
        km = a.get('km') or round(gpx_km, 1)
        k = find_join(points, lap)
        join_km = a.get('joinKm') or round(length(points[:k + 1]) * km / gpx_km, 1)
        course['approach'] = {'route': route_id, 'km': km, 'joinKm': join_km, 'joinName': a['joinName'],
                              'join': points[k][:2]}
        courses[c['id']] = course
        print(f"{c['id']}: loop {course['loop'] and course['loop']['km']} km, approach {km} km, "
              f"joins the circuit at km {join_km} ({a['joinName']})")
    out = ('// Generated by tools/build_route_data.py from data/gpx/*.gpx. Do not edit by hand.\n'
           '// routes: [lat, lon, elevation] points. courses: start place, optional loop, approach to the finish line.\n'
           'window.KK = window.KK || {};\n'
           f"KK.routeData = {json.dumps({'routes': routes, 'courses': courses}, separators=(',', ':'), ensure_ascii=False)};\n")
    open(os.path.join(ROOT, 'data', 'route-data.js'), 'w', encoding='utf-8').write(out)


if __name__ == '__main__':
    main()
